const BACKEND_EN: Array<[RegExp, string]> = [
  [/^connect failed: (.*)$/, "Connection failed: $1"],
  [/^jump connect failed: (.*)$/, "Jump host connection failed: $1"],
  [/^jump tunnel failed: (.*)$/, "Jump tunnel failed: $1"],
  [/^jump authentication failed$/, "Jump host authentication failed"],
  [/^authentication failed$/, "Authentication failed (wrong password/key, or 2FA required)"],
  [/^auth failed: (.*)$/, "Authentication failed: $1"],
  [/^已取消验证（或等待输入超时）$/, "Verification cancelled (or input timed out)"],
  [/^认证请求已过期或不存在$/, "Auth request expired or not found"],
  [/^连接本地 SSH Agent 失败（是否已执行 ssh-add\?）：(.*)$/, "Failed to connect to local SSH Agent (did you run ssh-add?): $1"],
  [/^SSH Agent 中没有可用密钥（请先 ssh-add 添加）$/, "No identities in SSH Agent (run ssh-add first)"],
  [/^读取 SSH Agent 身份失败：(.*)$/, "Failed to read SSH Agent identities: $1"],
  [/^跳板机不能是自身$/, "Jump host cannot be itself"],
  [/^跳板机不支持嵌套（仅支持一级跳板）$/, "Nested jump hosts not supported (single level only)"],
  [/^跳板机会话不存在（可能已被删除）$/, "Jump session not found (may have been deleted)"],
  [/^会话已加密，请先在「设置 → 安全」中输入主密码解锁后重试$/, "Session is encrypted, unlock it in Settings → Security first"],
  [/^跳板机会话已加密，请先在「设置 → 安全」中输入主密码解锁后重试$/, "Jump session is encrypted, unlock it in Settings → Security first"],
];

export function backendError(msg: string): string {
  if (getLang() !== "en") return msg;
  for (const [re, out] of BACKEND_EN) {
    if (re.test(msg)) return msg.replace(re, out);
  }
  return msg;
}

