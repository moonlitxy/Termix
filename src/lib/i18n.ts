const STRINGS: Record<Lang, Dict> = { zh, en };

export function t(key: string, vars?: Record<string, string | number>): string {
  const lang = getLang();
  let s = STRINGS[lang][key] ?? STRINGS.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** 语言切换时触发重渲染（设置页切换语言后全界面即时生效） */
export function useT(): typeof t {
  const [, bump] = useState(0);
  useEffect(() => {
    const onChange = () => bump((n) => n + 1);
    window.addEventListener(SETTINGS_CHANGE_EVENT, onChange);
    return () => window.removeEventListener(SETTINGS_CHANGE_EVENT, onChange);
  }, []);
  return t;
}

